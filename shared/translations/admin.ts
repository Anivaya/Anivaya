import type { Translator } from "../translations.ts";
import type { AdminRecord, AdminResource } from "../admin.ts";

/** The API reserves these two assignment destinations for teams, not individual members. */
export function adminAssignee(value: string | undefined, tr: Translator) {
  return value === "Support" || value === "Administrateur"
    ? tr(value)
    : value || "";
}

/** Only server-generated record titles are translated; authored titles and names stay raw. */
export function adminRecordTitle(
  resource: AdminResource,
  row: AdminRecord,
  tr: Translator,
) {
  const kind = resource === "alerts" ? row.resource : resource;
  if (kind === "history") return adminHistoryAction(row.name, tr);
  if (kind === "security" && row.kind !== "Session") return tr(row.name);
  if (kind === "deletions" && row.name.startsWith("Demande de "))
    return tr("Demande de {0}", [row.name.slice("Demande de ".length)]);
  if (kind === "appeals" && row.name === `Recours ${row.reference}`)
    return tr("Recours {0}", [row.reference]);
  return row.name;
}

/** Document names are interpolated after translating the action label. */
export function actionLabel(
  action: { id: string; label: string },
  tr: Translator,
) {
  return action.id.startsWith("proof:")
    ? tr("Vérifier : {0}", [action.label.slice("Vérifier : ".length)])
    : tr(action.label);
}

/** Audit actions are generated by the server. Names after the prefix stay untouched. */
export function adminHistoryAction(source: string, tr: Translator) {
  const match =
    /^(Invitation|Création|Alerte examinée|Contenu supprimé|Brouillon supprimé|Ticket d’incident|Ticket créé|Nouvelle décision|edit|save|publish|unpublish|submit|review|version|decide|reopen|priority|reply|retry|incident|ticket|proof|proof-file|delete|decline|renew|cancel|reset|revoke|read|unread) : ([\s\S]*)$/.exec(
      source,
    );
  if (!match) return tr(source);
  return tr(`${match[1]} : {0}`, [
    match[1] === "Nouvelle décision" ? tr(match[2]) : match[2],
  ]);
}
